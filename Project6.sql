INSERT INTO DIM_REGION (REGION_ID, REGION_NAME)
SELECT
    ROW_NUMBER() OVER (ORDER BY REGION_NAME),
    REGION_NAME
FROM (
    SELECT DISTINCT REGION_NAME
    FROM (
        SELECT REGION AS REGION_NAME
        FROM STG_BRANCHES

        UNION

        SELECT
            CASE
                WHEN STATE IN ('Telangana','Karnataka','Tamil Nadu','Andhra Pradesh','Kerala') THEN 'South'
                WHEN STATE IN ('Maharashtra','Gujarat') THEN 'West'
                WHEN STATE IN ('Delhi','Chandigarh','Rajasthan','Uttar Pradesh') THEN 'North'
                WHEN STATE IN ('West Bengal','Bihar') THEN 'East'
                WHEN STATE = 'Madhya Pradesh' THEN 'Central'
            END AS REGION_NAME
        FROM STG_CUSTOMERS
    )
    WHERE REGION_NAME IS NOT NULL
);

INSERT INTO DIM_STATE (STATE_ID, STATE_NAME, REGION_ID)
SELECT
    ROW_NUMBER() OVER (ORDER BY STATE_NAME),
    STATE_NAME,
    REGION_ID
FROM (
    SELECT DISTINCT
        X.STATE_NAME,
        R.REGION_ID
    FROM (
        SELECT
            STATE AS STATE_NAME,
            REGION AS REGION_NAME
        FROM STG_BRANCHES

        UNION

        SELECT
            STATE AS STATE_NAME,
            CASE
                WHEN STATE IN ('Telangana','Karnataka','Tamil Nadu','Andhra Pradesh','Kerala') THEN 'South'
                WHEN STATE IN ('Maharashtra','Gujarat') THEN 'West'
                WHEN STATE IN ('Delhi','Chandigarh','Rajasthan','Uttar Pradesh') THEN 'North'
                WHEN STATE IN ('West Bengal','Bihar') THEN 'East'
                WHEN STATE = 'Madhya Pradesh' THEN 'Central'
            END AS REGION_NAME
        FROM STG_CUSTOMERS
    ) X
    JOIN DIM_REGION R
        ON X.REGION_NAME = R.REGION_NAME
);

INSERT INTO DIM_CITY (CITY_ID, CITY_NAME, STATE_ID)
SELECT
    ROW_NUMBER() OVER (ORDER BY CITY_NAME, STATE_NAME),
    CITY_NAME,
    STATE_ID
FROM (
    SELECT DISTINCT
        X.CITY_NAME,
        X.STATE_NAME,
        S.STATE_ID
    FROM (
        SELECT CITY AS CITY_NAME, STATE AS STATE_NAME
        FROM STG_CUSTOMERS

        UNION

        SELECT CITY AS CITY_NAME, STATE AS STATE_NAME
        FROM STG_BRANCHES
    ) X
    JOIN DIM_STATE S
        ON X.STATE_NAME = S.STATE_NAME
);

INSERT INTO DIM_CATEGORY (CATEGORY_ID, CATEGORY_NAME)
SELECT
    ROW_NUMBER() OVER (ORDER BY CATEGORY_NAME),
    CATEGORY_NAME
FROM (
    SELECT DISTINCT CATEGORY AS CATEGORY_NAME
    FROM STG_PRODUCTS
);

INSERT INTO DIM_BRAND (BRAND_ID, BRAND_NAME, CATEGORY_ID)
SELECT
    ROW_NUMBER() OVER (ORDER BY BRAND_NAME, CATEGORY_ID),
    BRAND_NAME,
    CATEGORY_ID
FROM (
    SELECT DISTINCT
        P.BRAND AS BRAND_NAME,
        C.CATEGORY_ID
    FROM STG_PRODUCTS P
    JOIN DIM_CATEGORY C
        ON P.CATEGORY = C.CATEGORY_NAME
);

INSERT INTO DIM_YEAR (YEAR_ID, YEAR_VALUE)
SELECT
    ROW_NUMBER() OVER (ORDER BY YEAR_VALUE),
    YEAR_VALUE
FROM (
    SELECT DISTINCT YEAR AS YEAR_VALUE
    FROM STG_CALENDAR
);

INSERT INTO DIM_QUARTER (QUARTER_ID, QUARTER_NAME, YEAR_ID)
SELECT
    ROW_NUMBER() OVER (ORDER BY YEAR_VALUE, QUARTER_NAME),
    QUARTER_NAME,
    YEAR_ID
FROM (
    SELECT DISTINCT
        C.QUARTER AS QUARTER_NAME,
        C.YEAR AS YEAR_VALUE,
        Y.YEAR_ID
    FROM STG_CALENDAR C
    JOIN DIM_YEAR Y
        ON C.YEAR = Y.YEAR_VALUE
);

INSERT INTO DIM_MONTH (MONTH_ID, MONTH_NAME, QUARTER_ID)
SELECT
    ROW_NUMBER() OVER (ORDER BY YEAR_VALUE, QUARTER_NAME, MONTH_NAME),
    MONTH_NAME,
    QUARTER_ID
FROM (
    SELECT DISTINCT
        C.MONTH AS MONTH_NAME,
        C.QUARTER AS QUARTER_NAME,
        C.YEAR AS YEAR_VALUE,
        Q.QUARTER_ID
    FROM STG_CALENDAR C
    JOIN DIM_YEAR Y
        ON C.YEAR = Y.YEAR_VALUE
    JOIN DIM_QUARTER Q
        ON C.QUARTER = Q.QUARTER_NAME
        AND Q.YEAR_ID = Y.YEAR_ID
);

