CREATE OR REPLACE TABLE DIM_YEAR (
    YEAR_ID NUMBER PRIMARY KEY,
    YEAR_VALUE NUMBER
);

CREATE OR REPLACE TABLE DIM_QUARTER (
    QUARTER_ID NUMBER PRIMARY KEY,
    QUARTER_NAME VARCHAR(20),
    YEAR_ID NUMBER,
    FOREIGN KEY (YEAR_ID) REFERENCES DIM_YEAR(YEAR_ID)
