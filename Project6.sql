JOIN DIM_YEAR Y
    ON C.YEAR = Y.YEAR_VALUE
JOIN DIM_QUARTER Q
    ON C.QUARTER = Q.QUARTER_NAME
    AND Q.YEAR_ID = Y.YEAR_ID
JOIN DIM_MONTH M
    ON C.MONTH = M.MONTH_NAME
    AND M.QUARTER_ID = Q.QUARTER_ID;

