INSERT INTO DIM_DATE (
    DATE_ID,
    DATE_VALUE,
    DAY,
    DAY_NAME,
    WEEK_NO,
    MONTH_ID,
    IS_WEEKEND
)
SELECT
    C.DATE_ID,
    C.DATE_VALUE,
    C.DAY,
    C.DAY_NAME,
    C.WEEK_NO,
    M.MONTH_ID,
    C.IS_WEEKEND
